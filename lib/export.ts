import type { WorldMap } from './types'

type ExportableWorldMap = Pick<WorldMap, 'title' | 'synopsis' | 'concepts'>

function download(filename: string, content: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}

function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '') || 'study-guide'
}

export function exportStudyGuideMarkdown(worldMap: ExportableWorldMap) {
  const lines: string[] = [`# ${worldMap.title}`, '']

  if (worldMap.synopsis) {
    lines.push(worldMap.synopsis, '')
  }

  worldMap.concepts.forEach((c, i) => {
    lines.push(`## ${i + 1}. ${c.name}${c.completed ? ' ✓' : ''}`)
    lines.push(`*${c.difficulty} · ${c.xpReward} XP*`, '')
    lines.push(c.description, '')
  })

  lines.push('---', '_Generated by QuestScribe_')

  download(`${slugify(worldMap.title)}.md`, lines.join('\n'), 'text/markdown')
}

export async function exportStudyGuidePdf(worldMap: ExportableWorldMap) {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'pt', format: 'letter' })

  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 56
  const maxWidth = pageWidth - margin * 2
  let y = margin

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage()
      y = margin
    }
  }

  // Title
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(20)
  const titleLines = doc.splitTextToSize(worldMap.title, maxWidth)
  ensureSpace(titleLines.length * 26)
  doc.text(titleLines, margin, y)
  y += titleLines.length * 26 + 6

  // Synopsis
  if (worldMap.synopsis) {
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(11)
    doc.setTextColor(80)
    const synopsisLines = doc.splitTextToSize(worldMap.synopsis, maxWidth)
    ensureSpace(synopsisLines.length * 15 + 10)
    doc.text(synopsisLines, margin, y)
    y += synopsisLines.length * 15 + 20
    doc.setTextColor(0)
  }

  // Concepts
  worldMap.concepts.forEach((c, i) => {
    ensureSpace(60)

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(14)
    const heading = `${i + 1}. ${c.name}${c.completed ? '  (completed)' : ''}`
    const headingLines = doc.splitTextToSize(heading, maxWidth)
    doc.text(headingLines, margin, y)
    y += headingLines.length * 18

    doc.setFont('helvetica', 'italic')
    doc.setFontSize(9)
    doc.setTextColor(120)
    doc.text(`${c.difficulty} · ${c.xpReward} XP`, margin, y)
    doc.setTextColor(0)
    y += 16

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(11)
    const descLines = doc.splitTextToSize(c.description, maxWidth)
    ensureSpace(descLines.length * 15)
    doc.text(descLines, margin, y)
    y += descLines.length * 15 + 22
  })

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(150)
  doc.text('Generated by QuestScribe', margin, pageHeight - 28)

  doc.save(`${slugify(worldMap.title)}.pdf`)
}
